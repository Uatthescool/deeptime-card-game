/**
 * Every move a player can make, as plain serializable data. The UI dispatches
 * these; the same values can be logged, replayed, sent over a network, or
 * generated by an AI. `applyAction` is the single entry point that runs one.
 */
export type GameAction =
  | { type: "acknowledgeHandoff" }
  | { type: "chooseBiodiversityTop"; cardUid: string }
  | { type: "playCreature"; cardUid: string; laneIndex: number }
  | { type: "playAquaticOverride"; cardUid: string; laneIndex: number }
  | { type: "chooseConvergentCategory"; category: ConvergentCategory }
  | { type: "repositionWaterway"; sourceLane: number; destinationLane: number }
  | { type: "moveFacultative"; sourceLane: number; destinationLane: number }
  | { type: "playAdaptation"; cardUid: string; targetPlayer: PlayerId; laneIndex: number }
  | { type: "playEvent"; cardUid: string }
  | { type: "playWildfire"; cardUid: string; laneIndex: number }
  | { type: "playDrought"; cardUid: string; targetPlayer: PlayerId; laneIndex: number }
  | { type: "chooseGeologicalBoundary"; period: Period }
  | { type: "activateCarnianPluvial" }
  | { type: "chooseCarnianPluvial"; optionId: string }
  | { type: "playConcept"; cardUid: string }
  | { type: "chooseConceptOption"; optionId: string }
  | { type: "chooseHerd"; optionId: string }
  | { type: "chooseNesting"; optionId: string }
  | { type: "chooseFilterFeederTop"; cardUid: string }
  | { type: "chooseCranialDisplayTarget"; targetUid: string }
  | { type: "previewHunt"; attackerUid: string; defenderUid: string }
  | { type: "cancelHunt" }
  | { type: "flipBattleCoins" }
  | { type: "rerollBattleCoin"; playerId: PlayerId; group: CoinGroup; index: number }
  | { type: "commitHunt" }
  | { type: "chooseEngulf"; accept: boolean }
  | { type: "advanceToBattle" }
  | { type: "endTurn" }
  | { type: "fullHandMulligan" }
  | { type: "concede" };

export type GameActionType = GameAction["type"];

export function applyAction(state: GameState, action: GameAction): GameState {
  switch (action.type) {
    case "acknowledgeHandoff":
      return acknowledgeHandoff(state);
    case "chooseBiodiversityTop":
      return chooseBiodiversityTop(state, action.cardUid);
    case "playCreature":
      return playCreature(state, state.activePlayer, action.cardUid, action.laneIndex);
    case "playAquaticOverride":
      return playAquaticOverride(state, action.cardUid, action.laneIndex);
    case "chooseConvergentCategory":
      return chooseConvergentCategory(state, action.category);
    case "repositionWaterway":
      return repositionConnectedWaterway(state, action.sourceLane, action.destinationLane);
    case "moveFacultative":
      return moveFacultativeQuadrupedality(state, action.sourceLane, action.destinationLane);
    case "playAdaptation":
      return playAdaptation(state, action.cardUid, action.laneIndex, action.targetPlayer);
    case "playEvent":
      return playEvent(state, action.cardUid);
    case "playWildfire":
      return playWildfire(state, action.cardUid, action.laneIndex);
    case "playDrought":
      return playDrought(state, action.cardUid, action.targetPlayer, action.laneIndex);
    case "chooseGeologicalBoundary":
      return chooseGeologicalBoundaryPeriod(state, action.period);
    case "activateCarnianPluvial":
      return activateCarnianPluvialEpisode(state);
    case "chooseCarnianPluvial":
      return chooseCarnianPluvialOption(state, action.optionId);
    case "playConcept":
      return playConcept(state, action.cardUid);
    case "chooseConceptOption":
      return chooseConceptOption(state, action.optionId);
    case "chooseHerd":
      return chooseHerd(state, action.optionId);
    case "chooseNesting":
      return chooseNesting(state, action.optionId);
    case "chooseFilterFeederTop":
      return chooseFilterFeederTop(state, action.cardUid);
    case "chooseCranialDisplayTarget":
      return chooseCranialDisplayTarget(state, action.targetUid);
    case "previewHunt":
      return previewBattle(state, action.attackerUid, action.defenderUid);
    case "cancelHunt":
      return cancelBattlePreview(state);
    case "flipBattleCoins":
      return flipBattleCoins(state);
    case "rerollBattleCoin":
      return rerollBattleCoin(state, action.playerId, action.group, action.index);
    case "commitHunt":
      return commitBattle(state);
    case "chooseEngulf":
      return chooseEngulf(state, action.accept);
    case "advanceToBattle":
      return advanceToBattleOrEndTurn(state);
    case "endTurn":
      return endTurn(state);
    case "fullHandMulligan":
      return performFullHandMulligan(state);
    case "concede":
      return concedeByExtinction(state);
  }
}

/** Applies a sequence of actions in order — e.g. to replay a recorded game from its seed. */
export function replay(state: GameState, actions: readonly GameAction[]): GameState {
  return actions.reduce(applyAction, state);
}

/**
 * Every legal action in `state`, excluding conceding. While a choice is
 * pending, only actions that resolve it are listed. An empty list for a game
 * that is not over would mean the game is stuck — the simulation tests assert
 * that never happens.
 */
export function listLegalActions(state: GameState): GameAction[] {
  if (state.winner !== null) return [];
  if (state.handoff) return [{ type: "acknowledgeHandoff" }];
  if (state.pendingBiodiversity) {
    return state.pendingBiodiversity.cardUids.map((cardUid) => ({ type: "chooseBiodiversityTop", cardUid }));
  }
  if (state.pendingGeologicalBoundary) {
    return geologicalBoundaryOptions(state).map((period) => ({ type: "chooseGeologicalBoundary", period }));
  }
  if (state.pendingEngulf) {
    return [
      { type: "chooseEngulf", accept: true },
      { type: "chooseEngulf", accept: false },
    ];
  }
  if (state.pendingBattle) return battleActions(state);
  if (state.pendingConvergentChoice) {
    return state.pendingConvergentChoice.categories.map((category) => ({ type: "chooseConvergentCategory", category }));
  }
  if (state.pendingHerd) return getHerdOptions(state).map((option) => ({ type: "chooseHerd", optionId: option.id }));
  if (state.pendingNesting)
    return getNestingOptions(state).map((option) => ({ type: "chooseNesting", optionId: option.id }));
  if (state.pendingCranialDisplay) {
    return state.pendingCranialDisplay.eligibleTargetUids.map((targetUid) => ({
      type: "chooseCranialDisplayTarget",
      targetUid,
    }));
  }
  if (state.pendingFilterFeeder) {
    return state.pendingFilterFeeder.cardUids.map((cardUid) => ({ type: "chooseFilterFeederTop", cardUid }));
  }
  if (state.pendingConceptChoice) {
    return getConceptChoiceOptions(state).map((option) => ({ type: "chooseConceptOption", optionId: option.id }));
  }
  if (state.pendingCarnianPluvial) {
    return getCarnianPluvialOptions(state).map((option) => ({ type: "chooseCarnianPluvial", optionId: option.id }));
  }
  if (state.entryEffectQueue.length) return [];
  if (state.phase === "development") return developmentActions(state);
  if (state.phase === "battle") return [...huntActions(state), { type: "endTurn" }];
  return [];
}

function battleActions(state: GameState): GameAction[] {
  const battle = state.pendingBattle!;
  const coinCount = battle.coinPlan.offensiveCount + battle.coinPlan.defensiveCount;
  const cancel: GameAction[] = battle.origin === "stampede" || battle.coins ? [] : [{ type: "cancelHunt" }];
  if (coinCount > 0 && !battle.coins) return [{ type: "flipBattleCoins" }, ...cancel];
  const rerolls: GameAction[] = [];
  for (const group of ["offensive", "defensive"] as const) {
    (battle.coins?.[group] ?? []).forEach((_, index) => {
      for (const playerId of [0, 1] as const) {
        if (canRerollBattleCoin(state, playerId, group, index)) {
          rerolls.push({ type: "rerollBattleCoin", playerId, group, index });
        }
      }
    });
  }
  return [{ type: "commitHunt" }, ...rerolls, ...cancel];
}

function huntActions(state: GameState): GameAction[] {
  return state.players[state.activePlayer].lanes.flatMap((lane) =>
    lane.creature
      ? legalAttackTargets(state, lane.creature.card.uid).map((defenderUid): GameAction => ({
          type: "previewHunt",
          attackerUid: lane.creature!.card.uid,
          defenderUid,
        }))
      : [],
  );
}

function developmentActions(state: GameState): GameAction[] {
  const active = state.activePlayer;
  const player = state.players[active];
  const actions: GameAction[] = [];

  for (const card of player.hand) {
    const { kind, key } = card.definition;
    if (kind === "creature") {
      for (const laneIndex of legalCreatureLanes(state, active, card)) {
        actions.push({ type: "playCreature", cardUid: card.uid, laneIndex });
      }
      for (const laneIndex of legalAquaticOverrideLanes(state, card)) {
        actions.push({ type: "playAquaticOverride", cardUid: card.uid, laneIndex });
      }
    } else if (kind === "adaptation") {
      for (const target of legalAdaptationTargets(state, card)) {
        actions.push({
          type: "playAdaptation",
          cardUid: card.uid,
          targetPlayer: target.playerId,
          laneIndex: target.laneIndex,
        });
      }
    } else if (key === "wildfire") {
      for (const laneIndex of legalWildfireLanes(state, card))
        actions.push({ type: "playWildfire", cardUid: card.uid, laneIndex });
    } else if (key === "drought") {
      for (const target of legalDroughtTargets(state, card)) {
        actions.push({
          type: "playDrought",
          cardUid: card.uid,
          targetPlayer: target.playerId,
          laneIndex: target.laneIndex,
        });
      }
    } else if (kind === "event") {
      if (canPlayEvent(state, card)) actions.push({ type: "playEvent", cardUid: card.uid });
    } else if (canPlayConcept(state, card)) {
      actions.push({ type: "playConcept", cardUid: card.uid });
    }
  }

  for (const sourceLane of legalConnectedWaterwaySources(state)) {
    for (const destinationLane of legalConnectedWaterwayDestinations(state, sourceLane)) {
      actions.push({ type: "repositionWaterway", sourceLane, destinationLane });
    }
  }
  for (const sourceLane of legalFacultativeSources(state)) {
    for (const destinationLane of legalFacultativeDestinations(state, sourceLane)) {
      actions.push({ type: "moveFacultative", sourceLane, destinationLane });
    }
  }
  if (canActivateCarnianPluvialEpisode(state)) actions.push({ type: "activateCarnianPluvial" });
  if (canPerformFullHandMulligan(state)) actions.push({ type: "fullHandMulligan" });
  if (!player.allowances.rapidSpeciation) actions.push({ type: "advanceToBattle" });
  actions.push({ type: "endTurn" });
  return actions;
}

/** The player who must act next: the handoff recipient, the chooser of a pending choice, or the active player. */
export function actingPlayer(state: GameState): PlayerId {
  if (state.handoff) return state.handoff.to;
  if (state.pendingHerd) return state.pendingHerd.playerId;
  if (state.pendingNesting) return state.pendingNesting.playerId;
  if (state.pendingFilterFeeder) return state.pendingFilterFeeder.playerId;
  if (state.pendingBiodiversity) return state.pendingBiodiversity.playerId;
  if (state.pendingEngulf) return state.pendingEngulf.holderPlayer;
  return state.activePlayer;
}

/** The opponent of the player who must act next. */
export const waitingPlayer = (state: GameState): PlayerId => otherPlayer(actingPlayer(state));
